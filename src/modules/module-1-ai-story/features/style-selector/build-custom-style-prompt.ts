/**
 * 文件说明：模块 1 自定义风格抽取器提示词构造器。
 * 职责：根据学生输入生成交给外部 AI 的风格分析提示词，不调用任何模型接口。
 * 更新触发：抽取器提示词结构、输入转义或外部 AI 工作流文案口径变化时，需要同步更新本文件。
 */

export function buildModule1CustomStyleExtractorPrompt(inputText: string): string {
  return `你是一位文学风格分析师。  
任务：根据学生提供的一段文字，生成一张"自定义风格卡"。  

学生提供的内容如下（JSON 格式）：  
{
  "input_text": ${JSON.stringify(inputText)}
}

请你拆解并输出，严格遵循以下结构：  

【风格名称】  
一句简洁的风格标签（如"冷峻白描纪实""都市抒情隐喻""讽刺小品化"）。  

【风格特点】  
用 3–6 个短语，分号或顿号分隔，突出叙事手法/语气/句式/氛围。  

【示例语句】  
① 一句原创示例（保持该风格，不能抄原文）  
② 另一句原创示例（保持该风格，不能抄原文）  

注意：  
- 不得复刻或抄袭学生提供的文字；  
- 保持与输入文本风格一致；  
- 示例语句要短小、文学化，符合微小说开头风格；  
- 输出时保持卡片样式，方便直接放进课程支架。`
}
